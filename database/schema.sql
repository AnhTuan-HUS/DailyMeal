-- =========================================================
-- DATABASE: DailyMeal
-- DBMS: PostgreSQL
-- Description: Schema for DailyMeal web application (Using "users")
-- =========================================================

-- =========================================================
-- 1. MAIN ENTITIES
-- =========================================================

-- ROLE: Store system roles
CREATE TABLE role (
    role_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE,
    description TEXT
);

-- PERMISSION: Store system permissions
CREATE TABLE permission (
    permission_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT
);

-- USERS: Store user accounts (Dùng số nhiều 'users', không cần dấu ngoặc kép)
CREATE TABLE users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    user_name VARCHAR(100) NOT NULL,
    avatar_url TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    role_id INTEGER NOT NULL,
    CONSTRAINT fk_users_role
        FOREIGN KEY (role_id)
        REFERENCES role(role_id)
);

-- EATING_PROFILE: Store eating profiles managed by a user
CREATE TABLE eating_profile (
    profile_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id INTEGER NOT NULL,
    CONSTRAINT fk_eating_profile_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
);

-- INGREDIENT: Store ingredients
CREATE TABLE ingredient (
    ingredient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_name VARCHAR(100) NOT NULL,
    description TEXT,
    image_url TEXT
);

-- DISH_TYPE: Store dish types
CREATE TABLE dish_type (
    dish_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dish_type_name VARCHAR(100) NOT NULL UNIQUE
);

-- RECIPE: Store recipes
CREATE TABLE recipe (
    recipe_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_name VARCHAR(150) NOT NULL,
    description TEXT,
    instructions TEXT NOT NULL,
    cooking_time INTEGER NOT NULL,
    image_url TEXT,
    dish_type_id INTEGER NOT NULL,

    CONSTRAINT chk_recipe_cooking_time
        CHECK (cooking_time >= 0),

    CONSTRAINT fk_recipe_dish_type
        FOREIGN KEY (dish_type_id)
        REFERENCES dish_type(dish_type_id)
);

-- SHOPPING_LIST: Store users' shopping lists
CREATE TABLE shopping_list (
    shopping_list_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id INTEGER NOT NULL,

    CONSTRAINT fk_shopping_list_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
);

-- NUTRIENT: Store nutrient types
CREATE TABLE nutrient (
    nutrient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nutrient_name VARCHAR(100) NOT NULL UNIQUE
);

-- =========================================================
-- 2. ASSOCIATIVE ENTITIES
-- =========================================================

-- ROLE_PERMISSION: Many-to-many relationship between roles and permissions
CREATE TABLE role_permission (
    role_id INTEGER NOT NULL,
    permission_id INTEGER NOT NULL,

    CONSTRAINT pk_role_permission
        PRIMARY KEY (role_id, permission_id),

    CONSTRAINT fk_role_permission_role
        FOREIGN KEY (role_id)
        REFERENCES role(role_id),

    CONSTRAINT fk_role_permission_permission
        FOREIGN KEY (permission_id)
        REFERENCES permission(permission_id)
);

-- PROFILE_INGREDIENT_RESTRICTION: Ingredient restrictions for each eating profile
CREATE TABLE profile_ingredient_restriction (
    profile_id INTEGER NOT NULL,
    ingredient_id INTEGER NOT NULL,
    restriction_type VARCHAR(20) NOT NULL,

    CONSTRAINT pk_profile_ingredient_restriction
        PRIMARY KEY (profile_id, ingredient_id),

    CONSTRAINT chk_restriction_type
        CHECK (
            restriction_type IN (
                'ALLERGY',
                'CANNOT_EAT',
                'DISLIKE'
            )
        ),

    CONSTRAINT fk_profile_restriction_profile
        FOREIGN KEY (profile_id)
        REFERENCES eating_profile(profile_id),

    CONSTRAINT fk_profile_restriction_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES ingredient(ingredient_id)
);

-- INGREDIENT_NUTRIENT: Nutrient amounts for each ingredient
CREATE TABLE ingredient_nutrient (
    ingredient_id INTEGER NOT NULL,
    nutrient_id INTEGER NOT NULL,
    nutrient_amount DECIMAL(10,2) NOT NULL,

    CONSTRAINT pk_ingredient_nutrient
        PRIMARY KEY (ingredient_id, nutrient_id),

    CONSTRAINT chk_nutrient_amount
        CHECK (nutrient_amount >= 0),

    CONSTRAINT fk_ingredient_nutrient_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES ingredient(ingredient_id),

    CONSTRAINT fk_ingredient_nutrient_nutrient
        FOREIGN KEY (nutrient_id)
        REFERENCES nutrient(nutrient_id)
);

-- RECIPE_INGREDIENT: Ingredients used in each recipe
CREATE TABLE recipe_ingredient (
    recipe_id INTEGER NOT NULL,
    ingredient_id INTEGER NOT NULL,
    quantity DECIMAL(10,2) NOT NULL,
    unit VARCHAR(30) NOT NULL,

    CONSTRAINT pk_recipe_ingredient
        PRIMARY KEY (recipe_id, ingredient_id),

    CONSTRAINT chk_recipe_ingredient_quantity
        CHECK (quantity > 0),

    CONSTRAINT fk_recipe_ingredient_recipe
        FOREIGN KEY (recipe_id)
        REFERENCES recipe(recipe_id),

    CONSTRAINT fk_recipe_ingredient_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES ingredient(ingredient_id)
);

-- AVAILABLE_INGREDIENT: Ingredients currently available to each user
CREATE TABLE available_ingredient (
    user_id INTEGER NOT NULL,
    ingredient_id INTEGER NOT NULL,
    quantity DECIMAL(10,2) NOT NULL,
    unit VARCHAR(30) NOT NULL,

    CONSTRAINT pk_available_ingredient
        PRIMARY KEY (user_id, ingredient_id),

    CONSTRAINT chk_available_ingredient_quantity
        CHECK (quantity >= 0),

    CONSTRAINT fk_available_ingredient_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_available_ingredient_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES ingredient(ingredient_id)
);

-- SHOPPING_LIST_ITEM: Ingredients in shopping lists
CREATE TABLE shopping_list_item (
    shopping_list_id INTEGER NOT NULL,
    ingredient_id INTEGER NOT NULL,
    quantity DECIMAL(10,2) NOT NULL,
    unit VARCHAR(30) NOT NULL,
    is_purchased BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_shopping_list_item
        PRIMARY KEY (shopping_list_id, ingredient_id),

    CONSTRAINT chk_shopping_list_item_quantity
        CHECK (quantity > 0),

    CONSTRAINT fk_shopping_list_item_list
        FOREIGN KEY (shopping_list_id)
        REFERENCES shopping_list(shopping_list_id),

    CONSTRAINT fk_shopping_list_item_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES ingredient(ingredient_id)
);

