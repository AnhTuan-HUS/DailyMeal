-- =========================================================
-- DATABASE: DailyMeal
-- DBMS: PostgreSQL 16
-- Description: Schema chuẩn hóa tối ưu cho DailyMeal ("Hôm Nay Ăn Gì?")
-- Tổng số bảng: 20 bảng (11 thực thể chính + 1 thực thể yếu + 8 bảng liên kết)
-- =========================================================

-- Kích hoạt các extension cần thiết
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pg_trgm";

-- =========================================================
-- 1. CÁC BẢNG THỰC THỂ CHÍNH (STRONG ENTITIES)
-- =========================================================

-- ROLE: Vai trò người dùng (ADMIN, CONTENT_EDITOR, GENERAL_USER)
CREATE TABLE role (
    role_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE,
    description TEXT
);

-- PERMISSION: Danh mục quyền hạn
CREATE TABLE permission (
    permission_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT
);

-- USERS: Tài khoản người dùng
CREATE TABLE users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    user_name VARCHAR(100) NOT NULL,
    avatar_url TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    role_id INTEGER NOT NULL,
    CONSTRAINT fk_users_role
        FOREIGN KEY (role_id)
        REFERENCES role(role_id)
);

-- EATING_PROFILE: Hồ sơ ăn uống gia đình
CREATE TABLE eating_profile (
    profile_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_name VARCHAR(100) NOT NULL,
    is_child BOOLEAN NOT NULL DEFAULT FALSE,
    is_elderly BOOLEAN NOT NULL DEFAULT FALSE,
    spice_level INTEGER NOT NULL DEFAULT 2,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id INTEGER NOT NULL,
    CONSTRAINT chk_eating_profile_spice
        CHECK (spice_level >= 0 AND spice_level <= 5),
    CONSTRAINT fk_eating_profile_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE
);

-- DISH_TYPE: Vai trò món ăn trên mâm (main, soup, side, staple, appetizer_condiment, dessert)
CREATE TABLE dish_type (
    dish_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dish_type_name VARCHAR(100) NOT NULL UNIQUE
);

-- COOKING_METHOD: Phương pháp chế biến (braised, pan_fried, boiled_soup, stir_fried,...)
CREATE TABLE cooking_method (
    cooking_method_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_code VARCHAR(50) NOT NULL UNIQUE,
    method_name VARCHAR(100) NOT NULL,
    description TEXT
);

-- INGREDIENT: Danh mục nguyên liệu chuẩn hóa cố định (Master Data - Read-only)
CREATE TABLE ingredient (
    ingredient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    ingredient_name VARCHAR(150) NOT NULL,
    food_group VARCHAR(100) NOT NULL,
    market_stall VARCHAR(100) NOT NULL DEFAULT 'Quầy gia vị & đồ khô',
    waste_rate_percent DECIMAL(5,2) NOT NULL DEFAULT 0.0,
    description TEXT,
    image_url TEXT,
    CONSTRAINT chk_ingredient_waste_rate
        CHECK (waste_rate_percent >= 0.0 AND waste_rate_percent <= 100.0)
);

-- RECIPE: Công thức món ăn (chuẩn 1 khẩu phần)
CREATE TABLE recipe (
    recipe_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_name VARCHAR(200) NOT NULL,
    description TEXT,
    instructions TEXT NOT NULL,
    cooking_time INTEGER NOT NULL,
    servings INTEGER NOT NULL DEFAULT 1,
    image_url TEXT,
    source_url TEXT,
    dish_type_id INTEGER NOT NULL,
    cooking_method_id INTEGER NOT NULL,
    CONSTRAINT chk_recipe_cooking_time
        CHECK (cooking_time >= 0),
    CONSTRAINT chk_recipe_servings
        CHECK (servings > 0),
    CONSTRAINT fk_recipe_dish_type
        FOREIGN KEY (dish_type_id)
        REFERENCES dish_type(dish_type_id),
    CONSTRAINT fk_recipe_cooking_method
        FOREIGN KEY (cooking_method_id)
        REFERENCES cooking_method(cooking_method_id)
);

-- NUTRIENT: Danh mục chất dinh dưỡng
CREATE TABLE nutrient (
    nutrient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nutrient_name VARCHAR(100) NOT NULL UNIQUE,
    unit VARCHAR(20) NOT NULL DEFAULT 'g',
    description TEXT
);

-- SHOPPING_LIST: Danh sách mua sắm khi đi chợ
CREATE TABLE shopping_list (
    shopping_list_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_name VARCHAR(150) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id INTEGER NOT NULL,
    CONSTRAINT fk_shopping_list_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE
);

-- MEAL_HISTORY: Lịch sử mâm cơm đã chốt nấu (phục vụ chống lặp món 14 ngày)
CREATE TABLE meal_history (
    history_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_name VARCHAR(200) NOT NULL,
    cooked_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id INTEGER NOT NULL,
    CONSTRAINT fk_meal_history_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE
);

-- =========================================================
-- 2. BẢNG THỰC THỂ YẾU (WEAK ENTITY)
-- =========================================================

-- RECIPE_STEP: Từng bước nấu kèm ảnh chụp minh họa
CREATE TABLE recipe_step (
    step_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id INTEGER NOT NULL,
    step_number INTEGER NOT NULL,
    instruction_text TEXT NOT NULL,
    image_url TEXT,
    CONSTRAINT chk_step_number
        CHECK (step_number > 0),
    CONSTRAINT uq_recipe_step
        UNIQUE (recipe_id, step_number),
    CONSTRAINT fk_recipe_step_recipe
        FOREIGN KEY (recipe_id)
        REFERENCES recipe(recipe_id)
        ON DELETE CASCADE
);

-- =========================================================
-- 3. CÁC BẢNG KẾT HỢP NHIỀU - NHIỀU (ASSOCIATIVE ENTITIES)
-- =========================================================

-- ROLE_PERMISSION: Vai trò - Quyền hạn
CREATE TABLE role_permission (
    role_id INTEGER NOT NULL,
    permission_id INTEGER NOT NULL,
    CONSTRAINT pk_role_permission
        PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permission_role
        FOREIGN KEY (role_id)
        REFERENCES role(role_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_role_permission_permission
        FOREIGN KEY (permission_id)
        REFERENCES permission(permission_id)
        ON DELETE CASCADE
);

-- PROFILE_INGREDIENT_RESTRICTION: Hạn chế nguyên liệu theo hồ sơ (ALLERGY, CANNOT_EAT, DISLIKE)
CREATE TABLE profile_ingredient_restriction (
    profile_id INTEGER NOT NULL,
    ingredient_id INTEGER NOT NULL,
    restriction_type VARCHAR(20) NOT NULL,
    CONSTRAINT pk_profile_ingredient_restriction
        PRIMARY KEY (profile_id, ingredient_id),
    CONSTRAINT chk_restriction_type
        CHECK (restriction_type IN ('ALLERGY', 'CANNOT_EAT', 'DISLIKE')),
    CONSTRAINT fk_profile_restriction_profile
        FOREIGN KEY (profile_id)
        REFERENCES eating_profile(profile_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_profile_restriction_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES ingredient(ingredient_id)
        ON DELETE CASCADE
);

-- INGREDIENT_NUTRIENT: Thành phần dinh dưỡng trên 100g nguyên liệu
CREATE TABLE ingredient_nutrient (
    ingredient_id INTEGER NOT NULL,
    nutrient_id INTEGER NOT NULL,
    nutrient_amount DECIMAL(12,4) NOT NULL,
    CONSTRAINT pk_ingredient_nutrient
        PRIMARY KEY (ingredient_id, nutrient_id),
    CONSTRAINT chk_nutrient_amount
        CHECK (nutrient_amount >= 0),
    CONSTRAINT fk_ingredient_nutrient_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES ingredient(ingredient_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_ingredient_nutrient_nutrient
        FOREIGN KEY (nutrient_id)
        REFERENCES nutrient(nutrient_id)
        ON DELETE CASCADE
);

-- RECIPE_INGREDIENT: Nguyên liệu trong công thức (cho 1 khẩu phần)
CREATE TABLE recipe_ingredient (
    recipe_id INTEGER NOT NULL,
    ingredient_id INTEGER NOT NULL,
    quantity DECIMAL(10,2) NOT NULL,
    unit VARCHAR(30) NOT NULL,
    CONSTRAINT pk_recipe_ingredient
        PRIMARY KEY (recipe_id, ingredient_id),
    CONSTRAINT chk_recipe_ingredient_quantity
        CHECK (quantity > 0),
    CONSTRAINT fk_recipe_ingredient_recipe
        FOREIGN KEY (recipe_id)
        REFERENCES recipe(recipe_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_recipe_ingredient_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES ingredient(ingredient_id)
        ON DELETE RESTRICT
);

-- AVAILABLE_INGREDIENT: Thực phẩm sẵn có trong tủ lạnh gia đình
CREATE TABLE available_ingredient (
    user_id INTEGER NOT NULL,
    ingredient_id INTEGER NOT NULL,
    quantity DECIMAL(10,2) NOT NULL,
    unit VARCHAR(30) NOT NULL,
    expiry_date TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_available_ingredient
        PRIMARY KEY (user_id, ingredient_id),
    CONSTRAINT chk_available_ingredient_quantity
        CHECK (quantity >= 0),
    CONSTRAINT fk_available_ingredient_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_available_ingredient_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES ingredient(ingredient_id)
        ON DELETE CASCADE
);

-- SHOPPING_LIST_ITEM: Mục nguyên liệu cần mua sắm
CREATE TABLE shopping_list_item (
    shopping_list_id INTEGER NOT NULL,
    ingredient_id INTEGER NOT NULL,
    quantity DECIMAL(10,2) NOT NULL,
    unit VARCHAR(30) NOT NULL,
    is_purchased BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_shopping_list_item
        PRIMARY KEY (shopping_list_id, ingredient_id),
    CONSTRAINT chk_shopping_list_item_quantity
        CHECK (quantity > 0),
    CONSTRAINT fk_shopping_list_item_list
        FOREIGN KEY (shopping_list_id)
        REFERENCES shopping_list(shopping_list_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_shopping_list_item_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES ingredient(ingredient_id)
        ON DELETE CASCADE
);

-- MEAL_HISTORY_RECIPE: Danh sách các món ăn trong mâm cơm đã nấu
CREATE TABLE meal_history_recipe (
    history_id INTEGER NOT NULL,
    recipe_id INTEGER NOT NULL,
    CONSTRAINT pk_meal_history_recipe
        PRIMARY KEY (history_id, recipe_id),
    CONSTRAINT fk_meal_history_recipe_history
        FOREIGN KEY (history_id)
        REFERENCES meal_history(history_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_meal_history_recipe_recipe
        FOREIGN KEY (recipe_id)
        REFERENCES recipe(recipe_id)
        ON DELETE CASCADE
);

-- FAVORITE_RECIPE: Danh sách các món ăn yêu thích do người dùng lưu lại
CREATE TABLE favorite_recipe (
    user_id INTEGER NOT NULL,
    recipe_id INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_favorite_recipe
        PRIMARY KEY (user_id, recipe_id),
    CONSTRAINT fk_favorite_recipe_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_favorite_recipe_recipe
        FOREIGN KEY (recipe_id)
        REFERENCES recipe(recipe_id)
        ON DELETE CASCADE
);

-- =========================================================
-- 4. CHỈ MỤC TỐI ƯU HIỆU NĂNG TRUY VẤN (INDEXES)
-- =========================================================

CREATE INDEX idx_ingredient_code ON ingredient(code);
CREATE INDEX idx_ingredient_food_group ON ingredient(food_group);
CREATE INDEX idx_recipe_dish_cooking ON recipe(dish_type_id, cooking_method_id);
CREATE INDEX idx_recipe_cooking_time ON recipe(cooking_time);
CREATE INDEX idx_recipe_step_recipe_id ON recipe_step(recipe_id);
CREATE INDEX idx_available_expiry ON available_ingredient(user_id, expiry_date);
CREATE INDEX idx_meal_history_user_date ON meal_history(user_id, cooked_at DESC);
CREATE INDEX idx_shopping_list_user ON shopping_list(user_id);
CREATE INDEX idx_favorite_recipe_user ON favorite_recipe(user_id, created_at DESC);
